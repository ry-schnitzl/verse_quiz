#!/usr/bin/env python3
"""Draw the app's launcher icon: a stylized colon on a brown background.

Writes both kinds of icon from the one design below, so they always match:
  - drawable/ic_launcher_foreground.xml and ic_launcher_monochrome.xml, the
    vector layers of the adaptive icon (Android 8+).
  - mipmap-*/ic_launcher.webp and ic_launcher_round.webp, the bitmap icons
    for Android 7.x.
The background layer, drawable/ic_launcher_background.xml, is a solid BROWN.

Needs Pillow. Run from the project folder:
    python3 tools/make_icons.py
"""

from pathlib import Path

from PIL import Image, ImageDraw

RES = Path(__file__).resolve().parent.parent / "app" / "src" / "main" / "res"
SIZES = {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}

BROWN = "#6B4423"  # background
DOT = "#3A2210"  # the colon itself
# Stacked shadows behind each dot, nearest first: more golden and brighter
# the farther back they sit.
SHADOWS = ["#A87A2A", "#F2CB55"]
SHADOW_STEP = (2.0, 2.0)  # how far each shadow sits behind the one before it

# Positions in the 108-unit adaptive icon grid. The dots lean like an italic
# colon, and sit a little up and left so they and their shadows look centered.
DOTS = [(54, 39), (48, 63.5)]
RADIUS = 9
# Legacy icons show the middle 72 units of the 108-unit grid.
VISIBLE = (18, 90)


def layers():
    """(offset, color) for each layer, drawn back to front."""
    out = []
    for i, color in reversed(list(enumerate(SHADOWS, start=1))):
        out.append(((SHADOW_STEP[0] * i, SHADOW_STEP[1] * i), color))
    out.append(((0, 0), DOT))
    return out


def circles_path(offset):
    r = RADIUS
    return "".join(
        f"M{x + offset[0] - r:g},{y + offset[1]:g}"
        f"a{r:g},{r:g} 0,1 0,{2 * r:g} 0a{r:g},{r:g} 0,1 0,{-2 * r:g} 0z"
        for x, y in DOTS
    )


def vector(paths, comment):
    body = "".join(
        f'    <path\n        android:fillColor="{color}"\n'
        f'        android:pathData="{circles_path(offset)}" />\n'
        for offset, color in paths
    )
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        f"<!-- {comment} Generated by tools/make_icons.py. -->\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="108dp"\n'
        '    android:height="108dp"\n'
        '    android:viewportWidth="108"\n'
        '    android:viewportHeight="108">\n'
        f"{body}"
        "</vector>\n"
    )


def rgba(hex_color):
    return tuple(int(hex_color[i:i + 2], 16) for i in (1, 3, 5)) + (255,)


def draw_icon(size, round_shape):
    scale = 4  # draw large, then shrink for smooth edges
    big = size * scale
    unit = big / (VISIBLE[1] - VISIBLE[0])

    img = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    if round_shape:
        d.ellipse((0, 0, big - 1, big - 1), fill=rgba(BROWN))
    else:
        d.rounded_rectangle((0, 0, big - 1, big - 1), radius=big * 0.18, fill=rgba(BROWN))

    r = RADIUS * unit
    for offset, color in layers():
        for cx, cy in DOTS:
            x = (cx + offset[0] - VISIBLE[0]) * unit
            y = (cy + offset[1] - VISIBLE[0]) * unit
            d.ellipse((x - r, y - r, x + r, y + r), fill=rgba(color))

    return img.resize((size, size), Image.LANCZOS)


if __name__ == "__main__":
    drawable = RES / "drawable"
    (drawable / "ic_launcher_foreground.xml").write_text(
        vector(layers(), "A dark colon with stacked golden shadows."))
    (drawable / "ic_launcher_monochrome.xml").write_text(
        vector([((0, 0), "#FFFFFFFF")], "Themed icon (Android 13+): the colon alone, tinted by the system."))
    print(f"wrote {drawable} vectors")

    for density, size in SIZES.items():
        folder = RES / f"mipmap-{density}"
        draw_icon(size, round_shape=False).save(folder / "ic_launcher.webp", lossless=True)
        draw_icon(size, round_shape=True).save(folder / "ic_launcher_round.webp", lossless=True)
        print(f"wrote {folder} ({size}px)")
